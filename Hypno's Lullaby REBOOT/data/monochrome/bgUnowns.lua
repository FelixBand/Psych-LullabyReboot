function onUpdate(elapsed)
    if #bgUnowns == 0 then return end

    if not hasReferenceScroll then
        referenceScrollX = getProperty('camGame.scroll.x')
        referenceScrollY = getProperty('camGame.scroll.y')
        hasReferenceScroll = true
    end

    local songTime = getSongPosition() / 1000 + 1
    local zoom = math.max(0.001, getProperty('camGame.zoom'))
    local cameraX = getProperty('camGame.x') + 270
    local cameraY = getProperty('camGame.y') + 150
    local movementSpeed = 1
    if songTime >= 366.54166 then
        movementSpeed = 0
    elseif songTime >= 232.375 then
        movementSpeed = 2
    end

    local progress = getBgEyeProgress(songTime)
    local eyesVisible = areBgEyesVisible(songTime)
    if not eyesBlackened and songTime >= 92.958336 then
        for i = 1, #bgUnowns do
            setProperty(bgUnowns[i].tag .. '.color', '000000')
        end
        eyesBlackened = true
    end

    local intensity = 1
    if songTime >= 330.04166 then
        intensity = math.max(1, 15 - (14 * math.max(0, songTime - 330.04166) / (382.09 - 330.04166)))
    end

    for i = 1, #bgUnowns do
        local eye = bgUnowns[i]
        local staggerStart = ((i - 1) / (#bgUnowns - 1)) * 0.884
        local staggerEnd = staggerStart + 0.116
        local stagger = math.max(0, math.min(1, (progress - staggerStart) / (staggerEnd - staggerStart)))
        stagger = stagger * stagger * (3 - 2 * stagger)
        local alpha = eyesVisible and stagger or 0
        local time = songTime * movementSpeed * eye.speed
        local direction = eye.direction
        local side = eye.side
        local wobbleX = (math.cos(direction) * math.sin(time)) - (math.sin(direction) * math.cos(time * 0.85) * side)
        local wobbleY = (math.sin(direction) * math.sin(time)) + (math.cos(direction) * math.cos(time * 0.85) * side)
        local width = eye.width * eye.fill
        local height = eye.height * eye.fill

        local screenX = eye.x + ((eye.width - width) / 2) + (wobbleX * eye.amount * intensity)
        local screenY = eye.y + ((eye.height - height) / 2) + (wobbleY * eye.amount * intensity)
        local scrollX = referenceScrollX * eye.depth * 0.2
        local scrollY = referenceScrollY * eye.depth * 0.2

        setProperty(eye.tag .. '.x', ((screenX - cameraX) / zoom) + scrollX)
        setProperty(eye.tag .. '.y', ((screenY - cameraY) / zoom) + scrollY)
        scaleObject(eye.tag, (width / 134) / zoom, (height / 134) / zoom)
        setProperty(eye.tag .. '.alpha', alpha)
    end
end